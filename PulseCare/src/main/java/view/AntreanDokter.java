private void tampilkanAntrean() {

    DefaultTableModel model = new DefaultTableModel(
        new Object[]{
            "No. Antrean",
            "ID Kunjungan",
            "Nama Pasien",
            "Poliklinik",
            "Status",
            "Aksi"
        }, 0
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    jTable2.setModel(model);

    if (akunDokter == null) {
        return;
    }

    try {
        KunjunganDAO dao = new KunjunganDAO();

        // Mengambil antrean seluruh poliklinik hari ini
        List<Object[]> data =
                dao.antreanSemuaPoliDokterHariIni();

        for (Object[] row : data) {

            String status = row[4].toString();

            switch (status.toLowerCase()) {
                case "menunggu":
                    status = "Menunggu";
                    break;
                case "diperiksa":
                    status = "Sedang Diperiksa";
                    break;
                case "selesai":
                    status = "Selesai";
                    break;
                case "batal":
                    status = "Batal";
                    break;
            }

            model.addRow(new Object[]{
                row[0], // Nomor antrean
                row[1], // ID kunjungan
                row[2], // Nama pasien
                row[3], // Nama poliklinik
                status,
                "Periksa"
            });
        }

        jTable2.getColumnModel().getColumn(5)
            .setCellRenderer((table, value, selected, focus, row, col) -> {
                JButton tombol = new JButton("Periksa");
                return tombol;
            });

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Gagal memuat antrean: " + e.getMessage()
        );
    }
}
    private void bukaFormPemeriksaan(int baris) {
        try {
            String idKunjungan = jTable2.getValueAt(
                    baris, 1
            ).toString();

            KunjunganDAO dao = new KunjunganDAO();

            Object[] data = dao.detailKunjunganUntukPemeriksaan(
                    idKunjungan
            );

            if (data == null) {
                JOptionPane.showMessageDialog(this,
                        "Data kunjungan tidak ditemukan.");
                return;
            }

            MainFrame frame = (MainFrame)
                    javax.swing.SwingUtilities.getWindowAncestor(this);

            FormPemeriksaan form = frame.getFormPemeriksaan();

            form.setDataKunjungan(
                    data,
                    akunDokter.getNama(),
                    akunDokter.getNip()
            );

            frame.tampil("formPemeriksaan");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Gagal mengambil detail kunjungan: "
                    + e.getMessage());
        }
    }
