    private void jButton10ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton10ActionPerformed
        String keyword = jTextField1.getText().trim();

        if (keyword.isEmpty() || keyword.equals("Cari Nama Pasien")) {
            JOptionPane.showMessageDialog(this,
                    "Masukkan nama, ID, atau NIK pasien terlebih dahulu!");
            return;
        }

        try {
            PasienDAO dao = new PasienDAO();
            List<Pasien> hasil = dao.cari(keyword);

            if (hasil.isEmpty()) {
                pasienTerpilih = null;

                jLabel26.setText("Pasien tidak ditemukan");
                jLabel12.setText("-");
                jLabel13.setText("-");
                jLabel16.setText("-");
                jLabel23.setText("-");
                jLabel25.setText("-");

                JOptionPane.showMessageDialog(this,
                        "Data pasien tidak ditemukan.");
                return;
            }

            // Jika hasil pencarian lebih dari satu, pilih pasien
            int indeks = 0;

            if (hasil.size() > 1) {
                String[] pilihan = new String[hasil.size()];

                for (int i = 0; i < hasil.size(); i++) {
                    pilihan[i] = hasil.get(i).getNamaLengkap()
                            + " - " + hasil.get(i).getIdPasien();
                }

                String dipilih = (String) JOptionPane.showInputDialog(
                        this,
                        "Pilih pasien yang dimaksud:",
                        "Hasil Pencarian",
                        JOptionPane.QUESTION_MESSAGE,
                        null,
                        pilihan,
                        pilihan[0]
                );

                if (dipilih == null) {
                    return;
                }

                for (int i = 0; i < pilihan.length; i++) {
                    if (pilihan[i].equals(dipilih)) {
                        indeks = i;
                        break;
                    }
                }
            }

            pasienTerpilih = hasil.get(indeks);

            // Menampilkan data pasien
            jLabel26.setText(pasienTerpilih.getNamaLengkap());

            jLabel12.setText(pasienTerpilih.getIdPasien() + " - Belum ada");

            LocalDate tanggalLahir = pasienTerpilih.getTanggalLahir();

            int umur = Period.between(tanggalLahir, LocalDate.now()).getYears();

            String tanggal = tanggalLahir.format(
                    DateTimeFormatter.ofPattern("dd-MM-yyyy")
            );

            jLabel13.setText(tanggal + " (" + umur + " th)");

            jLabel16.setText(pasienTerpilih.getJenisKelamin());
            jLabel23.setText(pasienTerpilih.getStatusBpjs());
            jLabel25.setText("-");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Gagal mencari pasien: " + e.getMessage());
        }
    
    }//GEN-LAST:event_jButton10ActionPerformed

